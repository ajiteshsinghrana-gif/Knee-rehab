export const FORM_STRINGS: Record<Lang, Dict> = { en, hi, bn };
export function fs(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = FORM_STRINGS[lang][key] ?? en[key] ?? key;
  for (const [k, v] of Object.entries(params ?? {})) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export const fmtSize = (n: number): string => (n >= 1048576 ? `${(n / 1048576).toFixed(1)} MB` : `${Math.max(1, Math.round(n / 1024))} KB`);
